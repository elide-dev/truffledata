#!/usr/bin/env python3
"""Fold one Myna seam's per-ABI-class outputs into one set of bindings (bazel/myna.bzl).

Myna 0.14.0 makes C `char` signedness part of the target ABI class: x86-64 and Apple arm64 share
the LP64 little-endian signed-char class, aarch64-unknown-linux-gnu (AAPCS64) is its own class, and
each class has its own fingerprint. The generated code of the two classes is otherwise identical, so
one bindings jar can serve every target when it carries both fingerprints and selects by class:

  <Class>Abi.java   both fingerprints as constants and `fingerprint(boolean charUnsigned)`
  seam.h            the generated header with its ABI define selected by `__CHAR_UNSIGNED__`, the
                    compiler's own statement of the class criterion, so a C provider or consumer
                    compiled for any target gets its class's fingerprint
  abi/<class>/      each class's seam.abi and seam.json, for the contract check and tests

The tool fails if the two classes' generator outputs differ in anything but the fingerprint (and
the descriptor's `charUnsigned`): that would mean per-class bindings, not a shared jar.

usage: myna_abi.py --out DIR LP64_LITTLE_DIR LP64_LITTLE_AAPCS64_DIR
"""
import argparse
import hashlib
import json
import os
import re
import sys

HEX64 = re.compile(r'\b[0-9a-f]{64}\b')
DEFINE = re.compile(r'^#define (\w+_SEAM_ABI) "([0-9a-f]{64})"$')
TRIPLE = re.compile(r'^target triple = ".*"$', re.MULTILINE)

# Class name -> (descriptor targetAbi, representative triple, javadoc).
CLASSES = {
    'LP64_LITTLE': (
        {'dataModel': 'LP64', 'byteOrder': 'little'},
        'x86_64-unknown-linux-gnu',
        'LP64, little-endian, signed {@code char}: x86_64-unknown-linux-gnu, aarch64-apple-darwin.',
    ),
    'LP64_LITTLE_AAPCS64': (
        {'dataModel': 'LP64', 'byteOrder': 'little', 'charUnsigned': True},
        'aarch64-unknown-linux-gnu',
        'LP64, little-endian, unsigned {@code char} (AAPCS64 Linux): aarch64-unknown-linux-gnu.',
    ),
}


def read(path):
    with open(path, encoding='utf-8') as source:
        return source.read()


def load(name, directory):
    """One class's generator output: (descriptor, fingerprint, {file: text})."""
    files = {}
    for root, _dirs, names in os.walk(directory):
        for file in names:
            path = os.path.join(root, file)
            files[os.path.relpath(path, directory)] = read(path)
    for required in ('seam.json', 'seam.abi', 'seam.h'):
        if required not in files:
            sys.exit('%s: %s lacks %s' % (name, directory, required))
    fingerprint = files['seam.abi'].strip()
    if hashlib.sha256(files['seam.json'].encode('utf-8')).hexdigest() != fingerprint:
        sys.exit('%s: seam.abi is not the SHA-256 of seam.json' % name)
    descriptor = json.loads(files['seam.json'])
    if descriptor['targetAbi'] != CLASSES[name][0]:
        sys.exit('%s: descriptor targetAbi %s is not %s' % (name, descriptor['targetAbi'], CLASSES[name][0]))
    return descriptor, fingerprint, files


def normalized(file, text):
    """The generated text with its fingerprint and target triple folded, for the sameness check."""
    text = HEX64.sub('<ABI>', text)
    if file == 'seam.ll':
        text = TRIPLE.sub('target triple = "<TRIPLE>"', text)
    if file == 'seam.json':
        text = text.replace(',"charUnsigned":true', '')
    return text


def check_same(outputs):
    names = list(outputs)
    base_name, (_, _, base) = names[0], outputs[names[0]]
    for name in names[1:]:
        files = outputs[name][2]
        if set(files) != set(base):
            sys.exit('%s and %s generate different files: %s' % (base_name, name, sorted(set(files) ^ set(base))))
        for file in sorted(base):
            if normalized(file, base[file]) != normalized(file, files[file]):
                sys.exit('%s and %s differ in %s beyond the ABI fingerprint: the classes need separate bindings'
                         % (base_name, name, file))


def java(descriptor, fingerprints):
    package, name = descriptor['java']['package'], descriptor['java']['class'] + 'Abi'
    lines = [
        '// Generated by //bazel:myna_abi from the %s seam (Myna %s); do not edit.' % (descriptor['name'], descriptor['generatorVersion']),
        'package %s;' % package,
        '',
        '/**',
        ' * The ABI fingerprint of the {@code %s} seam for each Myna target ABI class. A native library' % descriptor['name'],
        ' * reports the fingerprint of the class it was built for; a consumer verifies it against the class',
        ' * it runs on (host-selected once on the JVM, folded at image build time on Native Image).',
        ' */',
        'public final class %s {' % name,
        '  private %s() {}' % name,
    ]
    for cls, (_abi, _triple, doc) in CLASSES.items():
        lines += ['', '  /** %s */' % doc, '  public static final String %s = "%s";' % (cls, fingerprints[cls])]
    lines += [
        '',
        '  /** The fingerprint of the ABI class whose C {@code char} is unsigned ({@code charUnsigned}) or signed. */',
        '  public static String fingerprint(boolean charUnsigned) {',
        '    return charUnsigned ? LP64_LITTLE_AAPCS64 : LP64_LITTLE;',
        '  }',
        '}',
        '',
    ]
    return name + '.java', '\n'.join(lines)


def header(text, fingerprints):
    """The signed-char class's seam.h with the ABI define selected by the compiler's char signedness."""
    lines = text.split('\n')
    defines = [i for i, line in enumerate(lines) if DEFINE.match(line)]
    if len(defines) != 1:
        sys.exit('seam.h holds %d ABI defines' % len(defines))
    macro, fingerprint = DEFINE.match(lines[defines[0]]).groups()
    if fingerprint != fingerprints['LP64_LITTLE']:
        sys.exit('seam.h define is not the LP64_LITTLE fingerprint')
    lines[defines[0]:defines[0] + 1] = [
        '/* The ABI class follows the C char signedness (Myna 0.14.0): unsigned on AAPCS64 Linux. */',
        '#ifdef __CHAR_UNSIGNED__',
        '#define %s "%s"' % (macro, fingerprints['LP64_LITTLE_AAPCS64']),
        '#else',
        '#define %s "%s"' % (macro, fingerprints['LP64_LITTLE']),
        '#endif',
    ]
    banner = '/* Generated by myna. ABI: %s */' % fingerprints['LP64_LITTLE']
    if lines[0] != banner:
        sys.exit('seam.h does not start with the generated ABI banner')
    lines[0] = '/* Generated by myna. ABI: %s (LP64_LITTLE), %s (LP64_LITTLE_AAPCS64) */' % (
        fingerprints['LP64_LITTLE'], fingerprints['LP64_LITTLE_AAPCS64'])
    return '\n'.join(lines)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as target:
        target.write(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--out', required=True, help='the bindings output directory (holds the target\'s seam.h)')
    for name in CLASSES:
        parser.add_argument(name.lower(), help='generator output for ' + name)
    args = parser.parse_args()
    outputs = {name: load(name, getattr(args, name.lower())) for name in CLASSES}
    check_same(outputs)
    fingerprints = {name: outputs[name][1] for name in CLASSES}
    if len(set(fingerprints.values())) != len(fingerprints):
        sys.exit('the ABI classes share a fingerprint; this tool is for Myna >= 0.14.0')
    descriptor = outputs['LP64_LITTLE'][0]
    file, text = java(descriptor, fingerprints)
    write(os.path.join(args.out, file), text)
    write(os.path.join(args.out, 'seam.h'), header(outputs['LP64_LITTLE'][2]['seam.h'], fingerprints))
    for name, (_descriptor, _fingerprint, files) in outputs.items():
        for copied in ('seam.abi', 'seam.json'):
            write(os.path.join(args.out, 'abi', name.lower(), copied), files[copied])
    print('myna_abi: %s %s' % (descriptor['name'], ', '.join('%s=%s' % item for item in fingerprints.items())))


if __name__ == '__main__':
    main()
