package dev.elide.truffledata.protobuf;

import com.google.protobuf.compiler.PluginProtos.*;
import dev.elide.truffledata.*;
import java.io.IOException;
import java.util.*;

/** protoc-gen-truffledata: emits Java contract literals, never serialized descriptors. */
public final class ContractPlugin {
  private ContractPlugin() {}

  public static void main(String[] args) throws IOException {
    byte[] request = System.in.readNBytes(64 * 1024 * 1024 + 1);
    CodeGeneratorResponse response;
    try {
      if (request.length > 64 * 1024 * 1024)
        throw new ContractViolation("Plugin request too large");
      response = generate(CodeGeneratorRequest.parseFrom(request));
    } catch (Exception error) {
      response =
          CodeGeneratorResponse.newBuilder()
              .setSupportedFeatures(CodeGeneratorResponse.Feature.FEATURE_PROTO3_OPTIONAL_VALUE)
              .setError(error.toString())
              .build();
    }
    response.writeTo(System.out);
  }

  public static CodeGeneratorResponse generate(CodeGeneratorRequest request) throws Exception {
    String packageName = "dev.elide.truffledata.generated", className = "TruffleDataContracts";
    if (!request.getParameter().isEmpty()) {
      for (String option : request.getParameter().split(",")) {
        String[] pair = option.split("=", -1);
        if (pair.length != 2) throw new ContractViolation("Expected package=... or class=...");
        switch (pair[0]) {
          case "package" -> packageName = pair[1];
          case "class" -> className = pair[1];
          default -> throw new ContractViolation("Unknown generator option: " + pair[0]);
        }
      }
    }
    if (!javax.lang.model.SourceVersion.isName(packageName)
        || !javax.lang.model.SourceVersion.isIdentifier(className)
        || javax.lang.model.SourceVersion.isKeyword(className))
      throw new ContractViolation("Invalid Java name");
    var roots = new ArrayList<com.google.protobuf.Descriptors.Descriptor>();
    for (var file : ProtoCompiler.files(request.getProtoFileList()))
      if (request.getFileToGenerateList().contains(file.getName()))
        roots.addAll(file.getMessageTypes());
    // Include otherwise unreferenced nested messages, too.
    for (int i = 0; i < roots.size(); i++) roots.addAll(roots.get(i).getNestedTypes());
    var definitions = ProtoCompiler.definitions(roots);
    StringBuilder source =
        new StringBuilder("// Generated by protoc-gen-truffledata.\npackage ")
            .append(packageName)
            .append(";\n")
            .append(
                "import dev.elide.truffledata.*;\n"
                    + "import dev.elide.truffledata.protobuf.ProtoPlan;\n")
            .append(
                "import java.util.*;\n@org.jspecify.annotations.NullMarked\npublic final class ")
            .append(className)
            .append(" {\n private ")
            .append(className)
            .append("() {}\n")
            .append(
                " public static ProtoPlan.Model"
                    + " create(com.oracle.truffle.api.@org.jspecify.annotations.Nullable"
                    + " TruffleLanguage<?> language, Limits limits, int maxDepth, int maxWireBytes)"
                    + " {\n")
            .append(" return new ProtoPlan.Model(language, List.of(");
    for (int i = 0; i < definitions.size(); i++) {
      if (i != 0) source.append(",");
      source.append("type").append(i).append("()");
    }
    source.append("), limits, maxDepth, maxWireBytes);\n }\n");
    for (int i = 0; i < definitions.size(); i++) {
      var type = definitions.get(i);
      source
          .append(" private static ProtoPlan.Type type")
          .append(i)
          .append("() { return new ProtoPlan.Type(")
          .append(quote(type.name()))
          .append(",")
          .append(type.mapEntry())
          .append(", List.of(");
      for (int j = 0; j < type.fields().size(); j++) {
        if (j != 0) source.append(",");
        source.append("field").append(i).append("_").append(j).append("()");
      }
      source.append(")); }\n");
      for (int j = 0; j < type.fields().size(); j++) {
        var f = type.fields().get(j);
        source
            .append(" private static ProtoPlan.FieldPlan field")
            .append(i)
            .append("_")
            .append(j)
            .append("() { return new ProtoPlan.FieldPlan(")
            .append(quote(f.name()))
            .append(",")
            .append(f.number())
            .append(",ProtoPlan.Kind.")
            .append(f.kind())
            .append(",")
            .append(f.repeated())
            .append(",")
            .append(f.map())
            .append(",")
            .append(f.explicitPresence())
            .append(",")
            .append(f.required())
            .append(",")
            .append(f.packed())
            .append(",")
            .append(f.oneof())
            .append(",")
            .append(quote(f.typeName()))
            .append(",");
        var e = f.enumType();
        if (e == null) source.append("null");
        else {
          source
              .append("new ProtoPlan.EnumType(")
              .append(quote(e.name()))
              .append(",")
              .append(e.open())
              .append(",Map.ofEntries(");
          boolean first = true;
          for (var entry : new TreeMap<>(e.values()).entrySet()) {
            if (!first) source.append(",");
            first = false;
            source
                .append("Map.entry(")
                .append(quote(entry.getKey()))
                .append(",")
                .append(entry.getValue())
                .append(")");
          }
          source.append("))");
        }
        source
            .append(",")
            .append(literal(f.defaultValue()))
            .append(",")
            .append(quote(f.jsonName()))
            .append("); }\n");
      }
    }
    source.append("}\n");
    return CodeGeneratorResponse.newBuilder()
        .setSupportedFeatures(CodeGeneratorResponse.Feature.FEATURE_PROTO3_OPTIONAL_VALUE)
        .addFile(
            CodeGeneratorResponse.File.newBuilder()
                .setName(packageName.replace('.', '/') + "/" + className + ".java")
                .setContent(source.toString()))
        .build();
  }

  private static String literal(Object value) throws Exception {
    if (value == Missing.INSTANCE) return "Missing.INSTANCE";
    if (value instanceof String s) return quote(s);
    if (value instanceof Boolean b) return b.toString();
    if (value instanceof Long n) return n + "L";
    if (value instanceof Double d)
      return "Double.longBitsToDouble(" + Double.doubleToRawLongBits(d) + "L)";
    if (value instanceof DataArray bytes) {
      byte[] array = new byte[bytes.size()];
      for (int i = 0; i < array.length; i++) array[i] = ((Long) bytes.get(i)).byteValue();
      return "DataArray.copyOfBytes(HexFormat.of().parseHex("
          + quote(HexFormat.of().formatHex(array))
          + "))";
    }
    return "Values.normalize(new java.math.BigInteger("
        + quote(
            com.oracle.truffle.api.interop.InteropLibrary.getUncached()
                .asBigInteger(value)
                .toString())
        + "))";
  }

  private static String quote(String value) {
    StringBuilder out = new StringBuilder("\"");
    for (char c : value.toCharArray()) {
      switch (c) {
        case '\\' -> out.append("\\\\");
        case '"' -> out.append("\\\"");
        case '\n' -> out.append("\\n");
        case '\r' -> out.append("\\r");
        default -> {
          if (c < 32 || c > 126) out.append(String.format("\\u%04x", (int) c));
          else out.append(c);
        }
      }
    }
    return out.append('"').toString();
  }
}
