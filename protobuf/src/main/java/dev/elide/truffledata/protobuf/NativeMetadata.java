package dev.elide.truffledata.protobuf;

import com.google.protobuf.DescriptorProtos;
import com.google.protobuf.JavaFeaturesProto;
import com.google.protobuf.Message;
import com.google.protobuf.ProtocolMessageEnum;
import com.oracle.truffle.api.CompilerDirectives.TruffleBoundary;
import java.lang.reflect.Modifier;
import java.lang.reflect.ParameterizedType;
import java.lang.reflect.Type;
import java.util.ArrayDeque;
import java.util.HashSet;
import java.util.Set;
import java.util.TreeSet;

/** Build-time reflection configuration for full-runtime Protobuf messages used by the adapter. */
public final class NativeMetadata {
  private NativeMetadata() {}

  /** Build-tool entry point. Arguments are binary message class names on the build classpath. */
  public static void main(String[] args) throws ClassNotFoundException {
    Class<?>[] roots = new Class<?>[args.length];
    for (int i = 0; i < args.length; i++) roots[i] = Class.forName(args[i]);
    System.out.print(reflectionConfig(roots));
  }

  /**
   * Emit deterministic Native Image reflection JSON for generated messages, their builders, enums
   * and imported message return types. Includes descriptor/edition support for DynamicMessage. Run
   * on the build JVM with consumer classes available, and package the returned JSON as
   * META-INF/native-image/GROUP/ARTIFACT/reflect-config.json. No runtime classpath scanning is
   * used. This supports the full Message API, not MessageLite-only generated classes or custom
   * reflection conventions. It does not configure JDBC drivers or automatically choose class
   * initialization.
   */
  @TruffleBoundary
  public static String reflectionConfig(Class<?>... messageClasses) {
    var pending = new ArrayDeque<Class<?>>();
    for (Class<?> root : messageClasses) {
      if (!Message.class.isAssignableFrom(root) || Modifier.isAbstract(root.getModifiers()))
        throw new IllegalArgumentException(
            "Expected a concrete full-runtime Protobuf message class");
      pending.add(root);
    }
    pending.add(DescriptorProtos.class);
    pending.add(JavaFeaturesProto.class);
    Set<Class<?>> visited = new HashSet<>();
    var names = new TreeSet<String>();
    while (!pending.isEmpty()) {
      Class<?> type = pending.removeFirst();
      if (!visited.add(type)) continue;
      if (visited.size() > 16384)
        throw new IllegalArgumentException("Protobuf metadata class budget exceeded");
      for (Class<?> nested : type.getDeclaredClasses()) {
        if (supported(nested)) pending.add(nested);
      }
      if (!supported(type) || Modifier.isAbstract(type.getModifiers())) continue;
      names.add(type.getName());
      for (var method : type.getDeclaredMethods()) {
        if (Modifier.isPublic(method.getModifiers()))
          collect(method.getGenericReturnType(), pending);
      }
    }
    var json = new StringBuilder("[\n");
    boolean first = true;
    for (String name : names) {
      if (!first) json.append(",\n");
      first = false;
      // Binary class names can contain non-Java-identifier characters in generated bytecode.
      json.append("  {\"name\":\"").append(escape(name)).append("\",\"allPublicMethods\":true}");
    }
    return json.append("\n]\n").toString();
  }

  private static boolean supported(Class<?> type) {
    return Message.class.isAssignableFrom(type)
        || Message.Builder.class.isAssignableFrom(type)
        || ProtocolMessageEnum.class.isAssignableFrom(type);
  }

  private static void collect(Type type, ArrayDeque<Class<?>> pending) {
    if (type instanceof Class<?> candidate) {
      if (supported(candidate)) pending.add(candidate);
    } else if (type instanceof ParameterizedType parameterized) {
      for (Type argument : parameterized.getActualTypeArguments()) collect(argument, pending);
    }
  }

  private static String escape(String value) {
    var result = new StringBuilder();
    for (int i = 0; i < value.length(); i++) {
      char c = value.charAt(i);
      if (c == '"' || c == '\\') result.append('\\').append(c);
      else if (c < 32) result.append(String.format("\\u%04x", (int) c));
      else result.append(c);
    }
    return result.toString();
  }
}
